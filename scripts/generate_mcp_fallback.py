#!/usr/bin/env python3
"""Regenerate the EMBEDDED_DATA fallback block inside functions/mcp.js.

The fallback is used by the MCP server only when its live same-origin data
fetch fails. It must never drift from the real data, so it is rebuilt from
api/v1/cities.json (plus fixed editorial statistics) and validated with
`node --check` before writing.

Run: python3 scripts/generate_mcp_fallback.py [--check]
  --check   exit 1 if the file would change (for tests/CI)
"""
import json, os, re, subprocess, sys

REPO = os.path.normpath(os.path.join(os.path.dirname(__file__), '..'))
CITIES_FILE = os.path.join(REPO, 'api', 'v1', 'cities.json')
MCP_FILE = os.path.join(REPO, 'functions', 'mcp.js')

# Fixed snapshot list (city diversity: England + Scotland, mixed sizes).
FALLBACK_CITIES = ['London', 'Leeds', 'Manchester', 'Edinburgh', 'Bristol', 'Birmingham', 'Glasgow']

# Editorial statistics that do not come from the FSA data feed.
STATIC_STATS = {
    'estimated_uk_market_size_gbp': '"£2.1B"',
    'growth_rate_2022_2025_pct': '20.3',
    'national_living_wage_april_2026': '12.71',
    'average_delivery_commission_uber_eats_pct': '30',
    'average_delivery_commission_deliveroo_pct': '32',
    'average_delivery_commission_just_eat_pct': '14',
    'average_delivery_markup_pct': '22',
    'typical_startup_cost_gbp': '{ min: 80000, max: 180000 }',
    'chef_visa_min_salary_gbp': '38700',
    'chef_visa_processing_weeks': '{ min: 12, max: 24 }',
}


def fmt_num(v: float) -> str:
    """Format numbers the way a JS literal would read naturally."""
    f = float(v)
    if f.is_integer():
        return str(int(f))
    return repr(f)


def build_block() -> str:
    data = json.load(open(CITIES_FILE))
    by_name = {c['name'].lower(): c for c in data['cities']}
    missing = [n for n in FALLBACK_CITIES if n.lower() not in by_name]
    if missing:
        raise SystemExit(f'city lookup failed for: {missing}')

    city_lines = []
    for name in FALLBACK_CITIES:
        c = by_name[name.lower()]
        fields = (
            f'name: "{c["name"]}"',
            f'population: {fmt_num(c["population"])}',
            f'total_thai_businesses: {fmt_num(c["total_thai_businesses"])}',
            f'restaurants: {fmt_num(c["restaurants"])}',
            f'takeaways: {fmt_num(c["takeaways"])}',
            f'per_100k: {fmt_num(c["per_100k"])}',
            f'avg_hygiene_rating: {fmt_num(c["avg_hygiene_rating"])}',
        )
        city_lines.append('    { ' + ', '.join(fields) + ' },')
    city_lines[-1] = city_lines[-1][:-1]  # no trailing comma on the last city

    stats_lines = [f'    total_uk_thai_businesses: {fmt_num(data.get("total_uk", 0))},']
    for key, val in STATIC_STATS.items():
        stats_lines.append(f'    {key}: {val},')
    # drop trailing comma on the last statistics entry
    stats_lines[-1] = stats_lines[-1].rstrip(',')

    block = (
        '// ── Embedded fallback data ──────────────────────────────────────────\n'
        '// AUTO-GENERATED by scripts/generate_mcp_fallback.py — refreshed weekly by\n'
        '// fsa_pipeline.py. Do not hand-edit; edit the generator instead.\n'
        'const EMBEDDED_DATA = {\n'
        '  name: "ThaiData UK",\n'
        '  cities: [\n'
        + '\n'.join(city_lines) + '\n'
        '  ],\n'
        '  statistics: {\n'
        + '\n'.join(stats_lines) + '\n'
        '  }\n'
        '};'
    )
    return block


BLOCK_RE = re.compile(
    r'// ── Embedded fallback data[\s\S]*?const EMBEDDED_DATA = \{[\s\S]*?\n\};'
)


def apply_block(js: str, block: str) -> str:
    new, n = BLOCK_RE.subn(lambda m: block, js, count=1)
    if n != 1:
        raise SystemExit('EMBEDDED_DATA block not found in functions/mcp.js')
    return new


def main() -> None:
    check = '--check' in sys.argv
    block = build_block()
    js = open(MCP_FILE).read()
    new_js = apply_block(js, block)

    if new_js == js:
        print('mcp.js fallback already current — nothing to do')
        return

    if check:
        print('mcp.js fallback is STALE (would change)')
        sys.exit(1)

    # validate before writing: node --check on a temp .js copy
    import tempfile
    fd, tmp = tempfile.mkstemp(suffix='.js', prefix='mcp-candidate-')
    os.close(fd)
    with open(tmp, 'w') as f:
        f.write(new_js)
    res = subprocess.run(['node', '--check', tmp], capture_output=True, text=True)
    os.unlink(tmp)
    if res.returncode != 0:
        raise SystemExit('candidate mcp.js failed node --check:\n' + res.stderr[:500])

    with open(MCP_FILE, 'w') as f:
        f.write(new_js)
    print('mcp.js fallback regenerated (node --check passed)')


if __name__ == '__main__':
    main()
